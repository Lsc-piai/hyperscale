def protected_names_rule(protected: list, default: str = "") -> str:
    """확정된 지명 목록을 '바꾸지 말 것' 규칙 문자열로 변환. 목록이 없으면 default 반환."""
    if not protected:
        return default
    names = "\n".join(f"  - {n}" for n in protected)
    return f"""- 아래 지명·상호명은 이미 공식 명칭으로 확정된 것이니, 철자·띄어쓰기 하나도
  바꾸지 말고 반드시 원문 그대로 유지할 것:
{names}"""


